// Regenerates vosk-worker.js from node_modules/vosk-browser (run after upgrading vosk-browser):
//   node src/renderer/modules/teleprompter/vosk/extract-worker.mjs
// vosk-browser starts its worker from a blob: URL, and a blob worker inherits the page's CSP,
// which forbids eval; the wasm glue (embind) needs `new Function`. A worker loaded from a real
// file has no CSP of its own, so the same code runs as a file next to the app.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const src = readFileSync(require.resolve("vosk-browser"), "utf8");
const marker = "createBase64WorkerFactory('";
const start = src.indexOf(marker) + marker.length;
const end = src.indexOf("'", start);
if (start < marker.length || end < 0) throw new Error("worker payload not found in vosk-browser");
const code = Buffer.from(src.slice(start, end), "base64").toString("utf8");
// same as vosk-browser's createURL: drop the loader's first line
const body = code.substring(code.indexOf("\n", 10) + 1);
const out = join(dirname(fileURLToPath(import.meta.url)), "vosk-worker.js");
writeFileSync(out, "/* eslint-disable */\n// GENERATED by extract-worker.mjs from vosk-browser. Do not edit.\n" + body);
console.log(`wrote ${out} (${(body.length / 1e6).toFixed(1)} MB)`);
